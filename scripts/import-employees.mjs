// Generates supabase/demo/seed.sql (the local preview's people and teams) and
// DEMO-LOGINS.md from an employee export CSV.
//
//   node scripts/import-employees.mjs "C:\path\to\employees.csv"
//
// Roles, passwords and team rules live in scripts/lib/employees.mjs.

import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { ADMIN_PASSWORD, COMPANY_TEAM, STAFF_PASSWORD, loadEmployees } from "./lib/employees.mjs";

const sql = (v) => (v === null || v === undefined || v === "" ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const note = (s) => String(s).replace(/\*\//g, "");

const csvPath = process.argv[2];
if (!csvPath) {
  console.error('Usage: node scripts/import-employees.mjs "path\\to\\employees.csv"');
  process.exit(1);
}
const { people, skipped, departments, owner, teams } = loadEmployees(csvPath);
const adminIds = people.filter((p) => p.role === "admin").map((p) => p.id);
const nameOf = new Map(people.map((p) => [p.id, p.name]));

const lines = [
  "-- DEMO MODE ONLY (in-browser database). GENERATED by scripts/import-employees.mjs",
  `-- from ${csvPath.split(/[\\/]/).pop()}. Do not edit by hand; re-run the script.`,
  `-- ${people.length} people, ${departments.length} departments, ${teams.length} department teams.`,
  "",
  "create function demo.as_user(p uuid) returns void language sql as $$",
  "  select set_config('request.jwt.claim.sub', coalesce(p::text, ''), false);",
  "$$;",
  "",
  "insert into public.departments (name) values",
  departments.map((d) => `  (${sql(d)})`).join(",\n") + ";",
  "",
  "-- People (account date = joining date where known)",
  "insert into auth.users (id, email, raw_user_meta_data, created_at) values",
  people
    .map(
      (p) =>
        `  /* ${note(p.empId)} */ (${sql(p.id)}, ${sql(p.email)}, ${sql(JSON.stringify({ display_name: p.name }))}, ${
          p.joined ? `${sql(p.joined)}::date` : "now()"
        })`,
    )
    .join(",\n") + ";",
  "",
  "update public.profiles p",
  "   set employment_status = v.status::public.employment_status,",
  "       title = v.title,",
  "       department_id = (select d.id from public.departments d where d.name = v.dept)",
  "  from (values",
  people.map((p) => `    (${sql(p.id)}, ${sql(p.status)}, ${sql(p.title)}, ${sql(p.dept)})`).join(",\n"),
  "  ) as v(id, status, title, dept)",
  " where p.id = v.id::uuid;",
  "",
  "update public.profile_details d set phone = v.phone, work_location = v.loc",
  "  from (values",
  people.map((p) => `    (${sql(p.id)}, ${sql(p.phone)}, ${sql(p.location)})`).join(",\n"),
  "  ) as v(id, phone, loc)",
  " where d.user_id = v.id::uuid;",
  "",
  "update public.user_roles r set role = v.role::public.app_role",
  "  from (values",
  people
    .filter((p) => p.role !== "employee")
    .map((p) => `    /* ${note(p.name)} */ (${sql(p.id)}, ${sql(p.role)})`)
    .join(",\n"),
  "  ) as v(id, role)",
  " where r.user_id = v.id::uuid;",
  "",
  "-- People who aren't active can't sign in.",
  "update auth.users u set banned_until = now() + interval '100 years'",
  "  from public.profiles p where p.id = u.id and p.employment_status in ('suspended', 'deactivated');",
  "",
  "-- Starting passwords: admins share one, everyone else another (changeable in Settings).",
  "insert into demo.credentials (user_id, password_hash)",
  "select id, encode(sha256(convert_to(",
  `         case when id in (${adminIds.map(sql).join(", ") || "null"})`,
  `              then ${sql(ADMIN_PASSWORD)} else ${sql(STAFF_PASSWORD)} end, 'UTF8')), 'hex')`,
  "  from auth.users;",
  "",
  "-- Company-wide team (public) ---------------------------------------------------",
  `select demo.as_user(${sql(owner.id)});`,
  "insert into public.teams (id, name, description, visibility, created_by) values",
  `  ('70000000-0000-4000-8000-000000000001', ${sql(COMPANY_TEAM)}, 'Company-wide announcements and discussion', 'public', ${sql(owner.id)});`,
  "insert into public.team_members (team_id, user_id)",
  "select '70000000-0000-4000-8000-000000000001', p.id from public.profiles p",
  ` where p.employment_status = 'active' and p.id <> ${sql(owner.id)};`,
  "",
  "-- One private team per department; department heads are its owners -------------",
];

for (const t of teams) {
  const [creator, ...otherOwners] = t.ownerIds;
  lines.push(
    `-- ${t.name}: owners ${t.ownerIds.map((id) => nameOf.get(id)).join(", ")}; ${t.memberIds.length} members`,
    `select demo.as_user(${sql(creator)});`,
    `insert into public.teams (id, name, description, visibility, created_by) values (${sql(t.id)}, ${sql(t.name)}, ${sql(
      `${t.name} department`,
    )}, 'private', ${sql(creator)});`,
  );
  const rows = [
    ...otherOwners.map((id) => `(${sql(t.id)}, ${sql(id)}, 'owner')`),
    ...t.memberIds.map((id) => `(${sql(t.id)}, ${sql(id)}, 'member')`),
  ];
  if (rows.length) lines.push(`insert into public.team_members (team_id, user_id, role) values\n  ${rows.join(",\n  ")};`);
  lines.push("");
}

lines.push(
  "update public.notifications set read_at = now() where kind = 'team_invite';",
  "select demo.as_user(null);",
  "drop function demo.as_user(uuid);",
  "insert into demo.meta (key, value) values ('seeded_at', now()::text);",
  "",
);

writeFileSync(join(process.cwd(), "supabase", "demo", "seed.sql"), lines.join("\n"));

// Login list for the local preview, kept in sync with the seed.
const ROLE_LABEL = { owner: "Owner", admin: "Admin", manager: "Manager", employee: "Employee" };
const ORDER = ["owner", "admin", "manager", "employee"];
const byRole = (a, b) => ORDER.indexOf(a.role) - ORDER.indexOf(b.role) || a.name.localeCompare(b.name);
const row = (p) => `| ${p.empId || "-"} | ${p.name} | ${p.email} | ${p.dept ?? "-"} | ${p.title ?? "-"} | ${ROLE_LABEL[p.role]} |`;
const table = (list) =>
  ["| Emp ID | Name | Login email (ID) | Department | Designation | Role |", "| --- | --- | --- | --- | --- | --- |", ...list.map(row)].join("\n");
const teamTable = [
  "| Team | Team owners | Members |",
  "| --- | --- | --- |",
  `| ${COMPANY_TEAM} (public, everyone) | ${owner.name} | ${people.filter((p) => p.status === "active").length} |`,
  ...teams.map((t) => `| ${t.name} (private) | ${t.ownerIds.map((id) => nameOf.get(id)).join(", ")} | ${t.ownerIds.length + t.memberIds.length} |`),
].join("\n");

const md = `# Diwakar Connect - local preview logins

Generated by \`scripts/import-employees.mjs\` from *${csvPath.split(/[\\/]/).pop()}*.
These accounts exist only in the **local preview** database inside your browser.
They don't exist in Supabase yet (see \`scripts/supabase-import.mjs\`).

Start the preview from this folder, then open **http://localhost:3000**:

\`\`\`bash
npm run demo:serve
\`\`\`

Everyone signs in with their **email** and starting password, and can change the
password under Settings → Account security. The **Admin** menu and admin
console are visible only to the owner and admins.

## Admins

**Password for admin accounts:** \`${ADMIN_PASSWORD}\`

${table(people.filter((p) => p.role === "admin").sort(byRole))}

## Everyone else

**Starting password:** \`${STAFF_PASSWORD}\`

${table(people.filter((p) => p.role !== "admin").sort(byRole))}

## Teams

Each department has a **private** team (only its members, plus admins for
management, can see it) with a General channel. Department heads - designations
containing Head, Manager, CFO or President - own their team; departments
without one are owned by ${owner.name}.

${teamTable}

## Notes

${skipped.length ? skipped.map((s) => `- Not imported: ${s}.`).join("\n") + "\n" : ""}- Owners can grant or remove the Admin role; admins manage managers and employees.
- Data is stored in this browser only; another browser gets its own fresh copy.
  To start over, clear this site's data in the browser (site settings for localhost:3000).
- Calls need a LiveKit media server, so they show "not available" here. No emails are sent.
`;
writeFileSync(join(process.cwd(), "DEMO-LOGINS.md"), md);

console.log(`Imported ${people.length} people across ${departments.length} departments; ${teams.length} department teams.`);
console.log("Roles:", people.filter((p) => p.role !== "employee").map((p) => `${p.name}=${p.role}`).join(", "));
for (const t of teams) console.log(`  team ${t.name}: owners ${t.ownerIds.map((id) => nameOf.get(id)).join(", ")}; +${t.memberIds.length} members`);
if (skipped.length) console.log("Skipped:\n  " + skipped.join("\n  "));
