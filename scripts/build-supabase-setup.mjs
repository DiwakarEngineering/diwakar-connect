// Builds ONE SQL file that fully sets up a fresh Supabase project from the
// Supabase SQL Editor - no database password or secret key needed:
//   * all migrations (tables, security policies, storage, realtime)
//   * departments, staff accounts (with starting passwords), roles, profiles
//   * the company team and one private team per department
//
//   node scripts/build-supabase-setup.mjs "C:\path\to\employees.csv"
//
// Output: supabase/setup/diwakar-connect-setup.sql (git-ignored: it contains
// the starting passwords). Paste it into SQL Editor -> New query -> Run.
// It runs in a single transaction: if anything fails, nothing is changed.

import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { COMPANY_TEAM, loadEmployees, uuidFor } from "./lib/employees.mjs";

const csvPath = process.argv[2];
if (!csvPath) {
  console.error('Usage: node scripts/build-supabase-setup.mjs "path\\to\\employees.csv"');
  process.exit(1);
}

const root = process.cwd();
const sql = (v) => (v === null || v === undefined || v === "" ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const { people, skipped, departments, owner, teams } = loadEmployees(csvPath);
const emailOf = new Map(people.map((p) => [p.id, p.email]));
const userId = (csvId) => `(select id from auth.users where lower(email) = ${sql(emailOf.get(csvId))})`;

const migrationFiles = readdirSync(join(root, "supabase", "migrations")).filter((f) => f.endsWith(".sql")).sort();

const out = [
  "-- Diwakar Connect - complete setup for a fresh Supabase project.",
  "-- GENERATED by scripts/build-supabase-setup.mjs. Paste into SQL Editor -> New query -> Run.",
  "-- Runs as one transaction: on any error nothing is changed. Run it only once.",
  "begin;",
  "",
];

for (const f of migrationFiles) {
  out.push(`-- ===== migration ${f} =====`, readFileSync(join(root, "supabase", "migrations", f), "utf8"), "");
}

out.push(
  "-- ===== record migrations (so the Supabase CLI knows they are applied) =====",
  "create schema if not exists supabase_migrations;",
  "create table if not exists supabase_migrations.schema_migrations (version text primary key, statements text[], name text);",
  "insert into supabase_migrations.schema_migrations (version, name) values",
  migrationFiles
    .map((f) => {
      const [version, ...rest] = f.replace(/\.sql$/, "").split("_");
      return `  (${sql(version)}, ${sql(rest.join("_"))})`;
    })
    .join(",\n"),
  "on conflict (version) do nothing;",
  "",
  "-- ===== departments =====",
  "insert into public.departments (name) values",
  departments.map((d) => `  (${sql(d)})`).join(",\n"),
  "on conflict do nothing;",
  "",
  "-- ===== staff accounts (email confirmed, starting password, no invite email) =====",
  "insert into auth.users (instance_id, id, aud, role, email, encrypted_password, email_confirmed_at,",
  "  raw_app_meta_data, raw_user_meta_data, created_at, updated_at,",
  "  confirmation_token, recovery_token, email_change_token_new, email_change,",
  "  email_change_token_current, reauthentication_token, phone_change, phone_change_token)",
  "select '00000000-0000-0000-0000-000000000000', v.id::uuid, 'authenticated', 'authenticated', v.email,",
  "       extensions.crypt(v.pw, extensions.gen_salt('bf')), now(),",
  `       '{"provider":"email","providers":["email"]}'::jsonb, jsonb_build_object('display_name', v.name),`,
  "       coalesce(v.joined::timestamptz, now()), now(), '', '', '', '', '', '', '', ''",
  "  from (values",
  people.map((p) => `    (${sql(p.id)}, ${sql(p.email)}, ${sql(p.name)}, ${sql(p.password)}, ${sql(p.joined)})`).join(",\n"),
  "  ) as v(id, email, name, pw, joined)",
  " where not exists (select 1 from auth.users u where lower(u.email) = lower(v.email));",
  "",
  "insert into auth.identities (id, user_id, provider_id, provider, identity_data, last_sign_in_at, created_at, updated_at)",
  "select gen_random_uuid(), u.id, u.id::text, 'email',",
  "       jsonb_build_object('sub', u.id::text, 'email', u.email, 'email_verified', true), null, now(), now()",
  "  from auth.users u",
  ` where lower(u.email) in (${people.map((p) => sql(p.email)).join(", ")})`,
  "   and not exists (select 1 from auth.identities i where i.user_id = u.id and i.provider = 'email');",
  "",
  "-- ===== profiles, contact details, roles =====",
  "update public.profiles p",
  "   set display_name = v.name, employment_status = v.status::public.employment_status, title = v.title,",
  "       department_id = (select d.id from public.departments d where d.name = v.dept)",
  "  from (values",
  people.map((p) => `    (${sql(p.email)}, ${sql(p.name)}, ${sql(p.status)}, ${sql(p.title)}, ${sql(p.dept)})`).join(",\n"),
  "  ) as v(email, name, status, title, dept)",
  "  join auth.users u on lower(u.email) = v.email",
  " where p.id = u.id;",
  "",
  "update public.profile_details d set phone = v.phone, work_location = v.loc",
  "  from (values",
  people.map((p) => `    (${sql(p.email)}, ${sql(p.phone)}, ${sql(p.location)})`).join(",\n"),
  "  ) as v(email, phone, loc)",
  "  join auth.users u on lower(u.email) = v.email",
  " where d.user_id = u.id;",
  "",
  "update public.user_roles r set role = v.role::public.app_role",
  "  from (values",
  people
    .filter((p) => p.role !== "employee")
    .map((p) => `    (${sql(p.email)}, ${sql(p.role)})`)
    .join(",\n"),
  "  ) as v(email, role)",
  "  join auth.users u on lower(u.email) = v.email",
  " where r.user_id = u.id;",
  "",
  "update auth.users u set banned_until = now() + interval '100 years'",
  "  from public.profiles p where p.id = u.id and p.employment_status in ('suspended', 'deactivated');",
  "",
  "-- ===== teams (the creator becomes owner and a General channel is added by a trigger) =====",
);

const allTeams = [
  {
    id: uuidFor(`team:${COMPANY_TEAM}`),
    name: COMPANY_TEAM,
    description: "Company-wide announcements and discussion",
    visibility: "public",
    ownerIds: [owner.id],
    memberIds: people.filter((p) => p.status === "active" && p.id !== owner.id).map((p) => p.id),
  },
  ...teams.map((t) => ({ ...t, description: `${t.name} department`, visibility: "private" })),
];
for (const t of allTeams) {
  const [creator, ...others] = t.ownerIds;
  out.push(
    `insert into public.teams (id, name, description, visibility, created_by)`,
    `select ${sql(t.id)}, ${sql(t.name)}, ${sql(t.description)}, ${sql(t.visibility)}, ${userId(creator)}`,
    ` where not exists (select 1 from public.teams where lower(name) = lower(${sql(t.name)}) and archived_at is null);`,
  );
  const rows = [
    ...others.map((id) => `(${userId(id)}, 'owner')`),
    ...t.memberIds.map((id) => `(${userId(id)}, 'member')`),
  ];
  if (rows.length) {
    out.push(
      "insert into public.team_members (team_id, user_id, role)",
      `select ${sql(t.id)}, v.user_id, v.role::public.team_member_role from (values`,
      "  " + rows.join(",\n  "),
      ") as v(user_id, role) where v.user_id is not null",
      "on conflict (team_id, user_id) do nothing;",
    );
  }
  out.push("");
}

out.push(
  "insert into public.audit_logs (action, target_type, metadata)",
  `values ('organization.staff_imported', 'organization', jsonb_build_object('people', ${people.length}, 'teams', ${allTeams.length}, 'via', 'sql_editor'));`,
  "",
  "commit;",
  "",
  "-- Check: should list 54 people with roles.",
  "select p.display_name, r.role, d.name as department",
  "  from public.profiles p join public.user_roles r on r.user_id = p.id",
  "  left join public.departments d on d.id = p.department_id",
  " order by r.role, p.display_name;",
  "",
);

const dir = join(root, "supabase", "setup");
mkdirSync(dir, { recursive: true });
const file = join(dir, "diwakar-connect-setup.sql");
writeFileSync(file, out.join("\n"));
console.log(`Wrote ${file}`);
console.log(`${people.length} people, ${departments.length} departments, ${allTeams.length} teams.`);
if (skipped.length) console.log("Skipped:\n  " + skipped.join("\n  "));
